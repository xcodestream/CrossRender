namespace {

ByteBuffer Fixture() {
    return ByteBuffer(std::begin(kFixtureZip), std::end(kFixtureZip));
}

// Эталон содержимого data/table.bin, сжатого в фикстуре.
ByteBuffer ExpectedTable() {
    ByteBuffer out;
    for (int i = 0; i < 100; ++i) {
        char buf[32];
        std::snprintf(buf, sizeof(buf), "CrossRender %04d; ", i);
        out.insert(out.end(), buf, buf + std::strlen(buf));
    }
    return out;
}

}  // namespace

ENG_TEST(Zip, ListEntries) {
    std::vector<std::string> names;
    ENG_CHECK(ZipListEntries(Fixture(), &names));
    ENG_CHECK_EQ(names.size(), usize{2});
    ENG_CHECK(names[0] == "readme.txt");
    ENG_CHECK(names[1] == "data/table.bin");
}

ENG_TEST(Zip, ReadStoredEntry) {
    ByteBuffer out;
    ENG_CHECK(ZipReadFile(Fixture(), "readme.txt", &out));
    std::string text(out.begin(), out.end());
    ENG_CHECK(text == "zip fixture\n");
}

ENG_TEST(Zip, ReadDeflatedEntry) {
    ByteBuffer out;
    ENG_CHECK(ZipReadFile(Fixture(), "data/table.bin", &out));
    ENG_CHECK_EQ(out.size(), ExpectedTable().size());
    ENG_CHECK(out == ExpectedTable());
}

ENG_TEST(Zip, MissingEntryFails) {
    ByteBuffer out;
    ENG_CHECK(!ZipReadFile(Fixture(), "nope.txt", &out));
    ENG_CHECK(!ZipReadFile(Fixture(), "data", &out));  // запись-каталог не файл
    ENG_CHECK(!ZipReadFile(ByteBuffer{}, "readme.txt", &out));
}

ENG_TEST(Zip, CorruptArchiveFails) {
    ByteBuffer truncated = Fixture();
    truncated.resize(truncated.size() / 2);
    std::vector<std::string> names;
    ENG_CHECK(!ZipListEntries(truncated, &names));
    ByteBuffer out;
    ENG_CHECK(!ZipReadFile(truncated, "readme.txt", &out));

    ByteBuffer garbled = Fixture();
    garbled[garbled.size() - 3] ^= 0xFF;  // ломаем размер центрального каталога
    ENG_CHECK(!ZipReadFile(garbled, "data/table.bin", &out));
}

ENG_TEST(Inflate, RejectsGarbage) {
    ByteBuffer out;
    const u8 junk[] = {0xFF, 0x00, 0xFF, 0x00, 0xFF, 0x00, 0xFF, 0x00};
    ENG_CHECK(!Inflate(junk, sizeof(junk), 0, &out));
    // Слишком большой вывод относительно expectedSize - предохранитель от порчи.
    ENG_CHECK(!Inflate(kFixtureZip + 0x50, 0xD9, 4, &out));
}

ENG_TEST(FileSystem, ReadsAssetsFromZip) {
    // Интеграция: assets.dat в корне ассетов отдаёт файлы через обычный VFS-доступ.
    const std::string savedRoot = GetAssetRoot();
    try {
        const std::string zipPath = test::TempFilePath("assets.dat");
        const std::string rootDir = PathDir(zipPath);
        SetAssetRoot(rootDir);
        ENG_CHECK(WriteBinaryFile(zipPath, kFixtureZip, sizeof(kFixtureZip)));

        ENG_CHECK(FileExists("assets/readme.txt"));
        ByteBuffer data = ReadBinaryFile("assets/readme.txt");
        ENG_CHECK(!data.empty());
        ENG_CHECK(std::string(data.begin(), data.end()) == "zip fixture\n");

        data = ReadBinaryFile("assets/data/table.bin");
        ENG_CHECK(data == ExpectedTable());

        // Листинг смешивает каталоги и файлы из архива.
        std::vector<std::string> listing = FS().ListDir("assets");
        bool hasReadme = false, hasData = false;
        for (const std::string& n : listing) {
            if (n == "readme.txt") hasReadme = true;
            if (n == "data") hasData = true;
        }
        ENG_CHECK(hasReadme);
        ENG_CHECK(hasData);

        // Нативные файлы по-прежнему приоритетны: пишем файл на диск поверх архива.
        ENG_CHECK(WriteTextFile(PathJoin(rootDir, "loose.txt"), "loose"));
        ENG_CHECK(ReadTextFile("loose.txt") == "loose");
        ENG_CHECK(ReadTextFile("assets/readme.txt") == "zip fixture\n");
    } catch (...) {
        SetAssetRoot(savedRoot);  // не ломаем корень ассетов для последующих тестов
        throw;
    }
    SetAssetRoot(savedRoot);
}

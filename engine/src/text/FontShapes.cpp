// Псевдографика/блочные глифы для отсутствующих кодовых символов.
constexpr u8 kBoxCell[7] = {0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F};
constexpr u8 kFillCell[7] = {0x1F, 0x1F, 0x1F, 0x1F, 0x1F, 0x1F, 0x1F};

const u8* FindOverride(u32 cp, u8 out[7]) {
    for (const LowerOverride& o : kLowerOverrides) {
        if (o.ch == cp) {
            for (int i = 0; i < 7; ++i) out[i] = o.rows[i];
            return out;
        }
    }
    return nullptr;
}

const u8* FindPunct(u32 cp, u8 out[7]) {
    for (const PunctGlyph& g : kPunct) {
        if (g.ch == cp) {
            for (int i = 0; i < 7; ++i) out[i] = g.rows[i];
            return out;
        }
    }
    return nullptr;
}

// Встроенный шрифт не покрывает кириллицу; наиболее частые кириллические
// буквы отображаются на визуально ближайшую латинскую ячейку, чтобы смешанный
// UI-текст оставался читаемым вместо рамок.
struct Translit {
    u32 cp;
    char latin;
};
constexpr Translit kCyrillic[] = {
    {0x0410, 'A'}, {0x0412, 'B'}, {0x0415, 'E'}, {0x041A, 'K'}, {0x041C, 'M'}, {0x041D, 'H'},
    {0x041E, 'O'}, {0x0420, 'P'}, {0x0421, 'C'}, {0x0422, 'T'}, {0x0423, 'Y'}, {0x0425, 'X'},
    {0x0430, 'a'}, {0x0432, 'b'}, {0x0435, 'e'}, {0x043A, 'k'}, {0x043C, 'm'}, {0x043D, 'h'},
    {0x043E, 'o'}, {0x0440, 'p'}, {0x0441, 'c'}, {0x0442, 't'}, {0x0443, 'y'}, {0x0445, 'x'},
    {0x0401, 'E'}, {0x0451, 'e'},
};


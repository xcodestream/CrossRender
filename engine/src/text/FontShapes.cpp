bool BuiltinGlyphRows(u32 codepoint, u8 rows[7]) {
    u8 tmp[7] = {0, 0, 0, 0, 0, 0, 0};

    u32 cp = codepoint;
    // Транслитерируем часть кириллицы, чтобы запасной шрифт оставался полезным.
    for (const Translit& t : kCyrillic) {
        if (t.cp == cp) {
            cp = static_cast<u32>(t.latin);
            break;
        }
    }

    if (cp == ' ') return true;  // валиден, но пуст (только шаг)
    if (cp == 0x2588 || cp == 0x25A0 || cp == 0x25AA) {  // блочные элементы
        for (int i = 0; i < 7; ++i) rows[i] = kFillCell[i];
        return true;
    }

    if (FindOverride(cp, tmp) != nullptr) {
        for (int i = 0; i < 7; ++i) rows[i] = tmp[i];
        return true;
    }
    if (FindPunct(cp, tmp) != nullptr) {
        for (int i = 0; i < 7; ++i) rows[i] = tmp[i];
        return true;
    }
    if (cp >= 0x20 && cp <= 0x5A) {
        const u8* cell = kUpperTable[cp - 0x20];
        for (int i = 0; i < 7; ++i) rows[i] = cell[i];
        return true;
    }
    if (cp >= 'a' && cp <= 'z') {
        const u8* cell = kUpperTable[static_cast<u32>('A') - 0x20 + (cp - 'a')];
        rows[0] = 0;
        rows[1] = 0;
        for (int i = 0; i < 5; ++i) rows[i + 2] = cell[i];
        return true;
    }
    if (cp == 0x00A0) return true;  // неразрывный пробел
    if (cp < 0x20 || cp == 0x7F) {
        for (int i = 0; i < 7; ++i) rows[i] = kBoxCell[i];
        return true;
    }
    // Неизвестный символ: полая рамка, чтобы вызывающий видел заметную метку «нет глифа».
    for (int i = 0; i < 7; ++i) rows[i] = kBoxCell[i];
    return true;
}

